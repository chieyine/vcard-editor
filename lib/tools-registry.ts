export type ToolWorkspace =
  | {
      kind:
        "editor" | "creator" | "compare" | "compatibility" | "pdf" | "fuzzy";
    }
  | { kind: "viewer"; table?: boolean }
  | { kind: "contact"; mode: ContactToolMode }
  | { kind: "conversion"; mode: ConversionMode; paste?: boolean }
  | {
      kind: "standards";
      mode: `${"from-vcard" | "to-vcard"}-${StandardsFormat}`;
    }
  | { kind: "text"; mode: "folder" | "unfolder" | "generator" }
  | { kind: "transform"; mode: "version" | "encoding" }
  | { kind: "qr"; mode: "single" | "batch" }
  | { kind: "reader"; camera: boolean }
  | { kind: "sqlite"; mode: "to-sqlite" | "from-sqlite" }
  | { kind: "photo"; mode: "compress" | "extract" | "view" };

